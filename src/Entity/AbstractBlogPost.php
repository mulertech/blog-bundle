<?php

declare(strict_types=1);

namespace MulerTech\BlogBundle\Entity;

use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use MulerTech\BlogBundle\Model\ReadingTime;
use MulerTech\FileBundle\Model\FileInterface;
use MulerTech\SeoBundle\Model\BlogPostingSeoInterface;
use Symfony\Component\Uid\Uuid;

/**
 * The fields every blog shares. Each site extends it with its own entity, which owns the
 * table and adds whatever only that site needs.
 *
 * One row is one article in one language: the versions of an article in several languages
 * are separate rows sharing a `translationGroup`. Each version therefore has its own slug,
 * publication date and view count, and a single-language site never sees anything more
 * than a column filled on its own.
 *
 * Column names are written out rather than left to the naming strategy, so the table a
 * site already has keeps its columns whatever strategy it uses.
 */
#[ORM\MappedSuperclass]
#[ORM\HasLifecycleCallbacks]
abstract class AbstractBlogPost implements BlogPostingSeoInterface
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    protected ?int $id = null;

    #[ORM\Column(length: 255)]
    protected string $title;

    /**
     * Unique per language rather than across the table: two versions of an article may
     * share a slug, a proper name for instance.
     */
    #[ORM\Column(length: 255)]
    protected string $slug;

    /**
     * Markdown.
     */
    #[ORM\Column(type: Types::TEXT)]
    protected string $content;

    #[ORM\Column(name: 'meta_description', length: 255, nullable: true)]
    protected ?string $metaDescription = null;

    /**
     * Plain text, a few sentences: shown on the article's card, and the description of
     * the article for search engines when it has no meta description.
     */
    #[ORM\Column(type: Types::TEXT, nullable: true)]
    protected ?string $excerpt = null;

    /**
     * Shows the label of the European Union on the article: a text generated by an AI and
     * published to inform the public must say so (AI Act, article 50 §4). The SQL default
     * gives the articles a table already holds the value of an article written by hand.
     */
    #[ORM\Column(name: 'ai_generated', options: ['default' => false])]
    protected bool $aiGenerated = false;

    #[ORM\ManyToOne(targetEntity: FileInterface::class)]
    #[ORM\JoinColumn(name: 'featured_image_id')]
    protected ?FileInterface $featuredImage = null;

    /**
     * @var Collection<int, FileInterface>
     */
    #[ORM\ManyToMany(targetEntity: FileInterface::class)]
    protected Collection $files;

    #[ORM\Column(name: 'is_published')]
    protected bool $isPublished = false;

    #[ORM\Column(name: 'published_at', type: Types::DATETIME_IMMUTABLE, nullable: true)]
    protected ?\DateTimeImmutable $publishedAt = null;

    /**
     * In minutes, derived from the content each time it changes.
     */
    #[ORM\Column(name: 'reading_time')]
    protected int $readingTime = 0;

    #[ORM\Column(name: 'view_count')]
    protected int $viewCount = 0;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_IMMUTABLE)]
    protected ?\DateTimeImmutable $createdAt = null;

    #[ORM\Column(name: 'updated_at', type: Types::DATETIME_IMMUTABLE, nullable: true)]
    protected ?\DateTimeImmutable $updatedAt = null;

    /**
     * A locale code such as `fr` or `en`, the one the article is written in.
     */
    #[ORM\Column(length: 10)]
    protected string $locale;

    #[ORM\Column(name: 'translation_group', type: Types::GUID)]
    protected string $translationGroup;

    /**
     * Mapped by BlogPostMetadataListener when the site names its category class, the one
     * this relation targets: a mapped superclass cannot point at a class it does not know.
     * Without it, the article has no category.
     */
    protected ?AbstractBlogCategory $category = null;

    /**
     * Mapped like `category`, when the site names its tag class. Built on first read
     * otherwise: Doctrine loads an article without calling its constructor, and fills only
     * what it maps.
     *
     * @var Collection<int, AbstractBlogTag>|null
     */
    protected ?Collection $tags = null;

    public function __construct()
    {
        $this->files = new ArrayCollection();
        $this->translationGroup = Uuid::v7()->toRfc4122();
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTitle(): string
    {
        return $this->title;
    }

    public function setTitle(string $title): static
    {
        $this->title = $title;

        return $this;
    }

    public function getSlug(): string
    {
        return $this->slug;
    }

    public function setSlug(string $slug): static
    {
        $this->slug = $slug;

        return $this;
    }

    public function getContent(): string
    {
        return $this->content;
    }

    public function setContent(string $content): static
    {
        $this->content = $content;
        $this->readingTime = ReadingTime::minutes($content);

        return $this;
    }

    public function getMetaDescription(): ?string
    {
        return $this->metaDescription;
    }

    public function setMetaDescription(?string $metaDescription): static
    {
        $this->metaDescription = $metaDescription;

        return $this;
    }

    public function getExcerpt(): ?string
    {
        return $this->excerpt;
    }

    public function setExcerpt(?string $excerpt): static
    {
        $this->excerpt = $excerpt;

        return $this;
    }

    public function isAiGenerated(): bool
    {
        return $this->aiGenerated;
    }

    public function setAiGenerated(bool $aiGenerated): static
    {
        $this->aiGenerated = $aiGenerated;

        return $this;
    }

    public function getFeaturedImage(): ?FileInterface
    {
        return $this->featuredImage;
    }

    public function setFeaturedImage(?FileInterface $featuredImage): static
    {
        $this->featuredImage = $featuredImage;

        return $this;
    }

    /**
     * @return Collection<int, FileInterface>
     */
    public function getFiles(): Collection
    {
        return $this->files;
    }

    public function addFile(FileInterface $file): static
    {
        if (!$this->files->contains($file)) {
            $this->files->add($file);
        }

        return $this;
    }

    public function removeFile(FileInterface $file): static
    {
        $this->files->removeElement($file);

        return $this;
    }

    public function getCategory(): ?AbstractBlogCategory
    {
        return $this->category;
    }

    public function setCategory(?AbstractBlogCategory $category): static
    {
        $this->category = $category;

        return $this;
    }

    /**
     * @return Collection<int, AbstractBlogTag>
     */
    public function getTags(): Collection
    {
        return $this->tags ??= new ArrayCollection();
    }

    public function addTag(AbstractBlogTag $tag): static
    {
        if (!$this->getTags()->contains($tag)) {
            $this->getTags()->add($tag);
        }

        return $this;
    }

    public function removeTag(AbstractBlogTag $tag): static
    {
        $this->getTags()->removeElement($tag);

        return $this;
    }

    public function isPublished(): bool
    {
        return $this->isPublished;
    }

    /**
     * The date of first publication: unpublishing then publishing again keeps it, so a
     * correction never moves an article to the top of the list. A date still to come is
     * that of a scheduled publication.
     */
    public function getPublishedAt(): ?\DateTimeImmutable
    {
        return $this->publishedAt;
    }

    /**
     * Whether a visitor reads it at `$now`: published, and its date reached.
     */
    public function isVisibleAt(\DateTimeImmutable $now): bool
    {
        return $this->isPublished && null !== $this->publishedAt && $this->publishedAt <= $now;
    }

    public function isScheduledAt(\DateTimeImmutable $now): bool
    {
        return $this->isPublished && null !== $this->publishedAt && $this->publishedAt > $now;
    }

    /**
     * Published at `$at` unless it was before: an article published now while it was
     * scheduled later takes the earlier date.
     */
    public function publish(\DateTimeImmutable $at): static
    {
        $this->isPublished = true;

        if (null === $this->publishedAt || $this->publishedAt > $at) {
            $this->publishedAt = $at;
        }

        return $this;
    }

    /**
     * Hidden from visitors until `$at`, then shown with that date, without any task to run.
     *
     * @throws \LogicException when the article was published before: it keeps its date
     */
    public function schedule(\DateTimeImmutable $at, \DateTimeImmutable $now): static
    {
        if ($at <= $now) {
            throw new \InvalidArgumentException(sprintf('A publication is scheduled in the future: %s is not after %s.', $at->format(\DATE_ATOM), $now->format(\DATE_ATOM)));
        }

        if (null !== $this->publishedAt && $this->publishedAt <= $now) {
            throw new \LogicException(sprintf('The article was published on %s and keeps that date: it cannot be scheduled.', $this->publishedAt->format(\DATE_ATOM)));
        }

        $this->isPublished = true;
        $this->publishedAt = $at;

        return $this;
    }

    public function unpublish(): static
    {
        $this->isPublished = false;

        return $this;
    }

    public function getReadingTime(): int
    {
        return $this->readingTime;
    }

    public function getViewCount(): int
    {
        return $this->viewCount;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function getUpdatedAt(): ?\DateTimeImmutable
    {
        return $this->updatedAt;
    }

    public function getLocale(): string
    {
        return $this->locale;
    }

    public function setLocale(string $locale): static
    {
        $this->locale = $locale;

        return $this;
    }

    public function getTranslationGroup(): string
    {
        return $this->translationGroup;
    }

    /**
     * Makes this article a version of `$original` in another language.
     */
    public function setTranslationOf(self $original): static
    {
        $this->translationGroup = $original->getTranslationGroup();

        return $this;
    }

    public function getSeoTitle(): string
    {
        return $this->title;
    }

    /**
     * The meta description, written for search engines, else the excerpt.
     */
    public function getSeoExcerpt(): ?string
    {
        return $this->metaDescription ?? $this->excerpt;
    }

    /**
     * Declared by each site, the only one knowing who writes: an author, the company.
     * Search engines show it with the article.
     */
    abstract public function getSeoAuthorName(): string;

    public function getSeoPublishedAt(): ?string
    {
        return $this->publishedAt?->format(\DATE_ATOM);
    }

    public function getSeoUpdatedAt(): ?string
    {
        return $this->updatedAt?->format(\DATE_ATOM);
    }

    #[ORM\PrePersist]
    public function initializeCreatedAt(): void
    {
        $this->createdAt ??= new \DateTimeImmutable();
    }

    #[ORM\PreUpdate]
    public function refreshUpdatedAt(): void
    {
        $this->updatedAt = new \DateTimeImmutable();
    }
}
